from contextvars import ContextVar
import utility_code
import match_lowlevel
from capstone import Cs, CS_ARCH_ARM, CS_MODE_ARM, CS_GRP_CALL
from wave20261102_child_fifth_index import candidates
from project import ROOT

ALLOWED = {'_ll_udiv', '_s32_div_f'}
ACTIVE = ContextVar('fifth_compiler_generated_imports', default={})
BASE = match_lowlevel.symbol_address


def resolve(name):
    bindings = ACTIVE.get()
    return bindings[name] if name in bindings else BASE(name)


match_lowlevel.symbol_address = resolve


def qualify(rows, spec, native):
    index = {(r['processor'], r['address']): r for r in candidates()}
    decoder = Cs(CS_ARCH_ARM, CS_MODE_ARM)
    decoder.detail = True
    bindings = {}
    for row in rows:
        name, offset = row['symbol'], row['offset']
        if name not in ALLOWED or row['type'] not in (1, 28, 29) or spec['processor'] != 'arm7' or spec['mode'] != 'arm':
            raise ValueError('Unqualified generated compiler import')
        instruction = next(decoder.disasm(native[offset:offset + 4], spec['address'] + offset), None)
        if instruction is None or not instruction.group(CS_GRP_CALL) or instruction.mnemonic.startswith('blx') or instruction.operands[0].type != 2:
            raise ValueError('Generated compiler import lacks an original direct ARM call')
        address = instruction.operands[0].imm & 0xffffffff
        target = index.get(('arm7', address))
        if target is None or target['program'] != spec['program'] or target['mode'] != 'arm':
            raise ValueError('Generated compiler import lacks an existing same-program ARM7/ARM boundary')
        if row.get('target') and int(row['target'], 0) != address:
            raise ValueError('Frozen generated compiler import target changed')
        if name in bindings and bindings[name] != address:
            raise ValueError('One generated compiler import has conflicting original call targets')
        bindings[name] = address
    return bindings


def infer(origin, spec, native):
    rows = [r for r in origin['relocations'] if r['symbol'] in ALLOWED]
    if not rows:
        return []
    bindings = qualify(rows, spec, native)
    return [dict(symbol=r['symbol'], offset=r['offset'], type=r['type'], addend=r['addend'],
        target=hex(bindings[r['symbol']]), targetMode='arm', originalBranchHex=native[r['offset']:r['offset'] + 4].hex(),
        source='Generated by the pinned C compiler; bound only to the measured original direct-call entry',
        calleePrototypeOrArityGuessed=False, calleeFunctionCredit=0, calleeSourceByteCredit=0,
        originalCalleeMeaningOrBehaviorProved=False) for r in rows]


def compile_compare(source, spec, optimization, inline, speed, rows):
    raw = (ROOT / spec['binary']).read_bytes()
    native = raw[spec['address'] - spec['base']:spec['address'] - spec['base'] + spec['bytes']]
    bindings = qualify(rows, spec, native) if rows else {}
    token = ACTIVE.set(bindings)
    try:
        return utility_code.compile_compare(source, spec, optimization, inline, speed)
    finally:
        ACTIVE.reset(token)
