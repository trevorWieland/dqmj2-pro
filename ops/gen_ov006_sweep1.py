"""Generate the sweep-1 lane: one address-named translation unit per ov006 row.

Two forms, decided by the plan (``ops/ov006_sweep1_plan.json``):

* ``generated``: the six members of the ``A6`` coarse-skeleton family, emitted from
  one C template whose only per-row inputs are the three resource-descriptor
  pointers decoded from the row's own literal pool.  The representative was read
  from the image and its C body matched byte-exactly on the first compile.
* ``transcribed``: the measured instruction stream in mwccarm ``asm`` form, one
  address-named file per row, generated by ``ops/transcribe_chunk.py``.

The generator is deterministic: the plan pins the addresses and the image is the
only other input, so ``--write`` always recreates the identical lane.

    python ops/gen_ov006_sweep1.py --list
    python ops/gen_ov006_sweep1.py --write
    python ops/gen_ov006_sweep1.py --write --only 0x21f7a10
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(ROOT / 'public_tools'))

import transcribe_chunk  # noqa: E402

IMAGE_PATH = ROOT / 'extract/arm9_overlays/ov006.bin'
BASE = 0x021D7240
LANE = Path('src/ov006/g1_ov006_sweep1')
PLAN = Path(__file__).resolve().parent / 'ov006_sweep1_plan.json'

# A6: six 112-byte Thumb functions.  Each registers three descriptor pairs and
# then sets the low two bits of five display-control halfwords on the sub engine
# (0x04001008, +2) and the main engine (0x04000008, +2, +4).  Pool words 0, 2 and
# 4 are the descriptor pointers that differ between the six; the rest are shared.
A6_TEMPLATE = '''/* ov006 row 0x{address:08x}: {size} bytes.
 *
 * What it does (from the measured stream): registers three resource descriptors
 * through the shared helper at 0x{helper:08x}, then forces the low two bits of
 * five display-control halfwords to 3: two on the sub engine at 0x04001008 and
 * three on the main engine at 0x04000008.  The helper's contract and the five
 * registers' meanings are not established by byte identity.
 *
 * Generated, not hand-written: this is member {member} of a six-row
 * coarse-skeleton family (identical opcode/register/width skeleton, only the
 * literal-pool pointers differ).  The representative 0x021f7a10 matched its C
 * body byte- and relocation-exactly on the first compile; the other five were
 * instantiated from the same template with the pointers read from their own
 * pool.  Rule: src/ov006/g1_ov006_sweep1/thumb/** (p033, mwccarm 2.0/sp1p5).
 *
 * Unknowns: what the three descriptors configure, and which engine consumer
 * reads the five control halfwords.
 */
typedef unsigned short u16;
typedef unsigned int u32;

extern void fn_021f27d4(u32 a, u32 b);

void native_ov006_{address:08x}(void)
{{
    fn_021f27d4(0x{descriptor0:08x}, 0x{register0:08x});
    fn_021f27d4(0x{descriptor1:08x}, 0x{register1:08x});
    fn_021f27d4(0x{descriptor2:08x}, 0x{register2:08x});
    *(volatile u16 *)0x04001008 = (*(volatile u16 *)0x04001008 & ~3u) | 3u;
    *(volatile u16 *)0x0400100a = (*(volatile u16 *)0x0400100a & ~3u) | 3u;
    *(volatile u16 *)0x04000008 = (*(volatile u16 *)0x04000008 & ~3u) | 3u;
    *(volatile u16 *)0x0400000a = (*(volatile u16 *)0x0400000a & ~3u) | 3u;
    *(volatile u16 *)0x0400000c = (*(volatile u16 *)0x0400000c & ~3u) | 3u;
}}
'''

A6_PURPOSE = 'registers three descriptor pairs and forces five display-control fields to 3'
A6_UNKNOWNS = ('what the three descriptors configure, which engine consumer reads the five '
               'control halfwords, and the helper contract at 0x021f27d4.')


def ledger_row(module, address):
    for line in (ROOT / 'ledger/functions.jsonl').open(encoding='utf-8'):
        if not line.strip():
            continue
        row = json.loads(line)
        if row['module'] == module and int(row['address'], 16) == address:
            return row
    raise SystemExit('row %s:%s not in the ledger' % (module, hex(address)))


def slot_words(address, size):
    """Every literal slot inside the row, in instruction order (pool words)."""
    image = IMAGE_PATH.read_bytes()
    code = image[address - BASE:address - BASE + size]
    if (int.from_bytes(code[:2], 'little') & 0xF800) == 0xF000:
        slots = transcribe_chunk.thumb_literal_slots(code, address)
    else:
        slots = transcribe_chunk.thumb_literal_slots(code, address)
    return [int.from_bytes(image[slot - BASE:slot - BASE + 4], 'little')
            for at, slot in sorted(slots.items()) if address <= slot < address + size]


def a6_source(address, member):
    row = ledger_row('ov006', address)
    size = int(row['bytes'])
    words = slot_words(address, size)
    if len(words) < 8:
        raise SystemExit('A6 row %s: %d pool words, expected 8' % (hex(address), len(words)))
    return A6_TEMPLATE.format(address=address, size=size, member=member,
                              helper=0x021F27D4,
                              descriptor0=words[0], register0=words[1],
                              descriptor1=words[2], register1=words[3],
                              descriptor2=words[4], register2=words[5])


def asm_source(address):
    row = ledger_row('ov006', address)
    return transcribe_chunk.emit('ov006', row, None,
                                 'byte identity proves the instruction stream, not the '
                                 'meaning of the fields, blocks and callee contracts it touches.')


def lane_path(address, mode):
    return ROOT / LANE / mode / 'ov006' / ('native_ov006_%08x.c' % address)


def plan():
    return json.loads(PLAN.read_text())


def write(only=None):
    data = plan()
    written = 0
    for index, key in enumerate(data['c']):
        address = int(key, 16)
        if only and address not in only:
            continue
        path = lane_path(address, 'thumb')
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(a6_source(address, index), encoding='ascii')
        written += 1
    for key in data['asm']:
        address = int(key, 16)
        if only and address not in only:
            continue
        row = ledger_row('ov006', address)
        path = lane_path(address, row['mode'])
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(asm_source(address), encoding='ascii')
        written += 1
    print('written %d files under %s' % (written, LANE))


def listing():
    data = plan()
    total = 0
    for form, key in [('generated', 'c'), ('transcribed', 'asm')]:
        for address in data[key]:
            row = ledger_row('ov006', int(address, 16))
            total += int(row['bytes'])
            print('%-11s 0x%s %4d B %s' % (form, address, int(row['bytes']), row['mode']))
    print('%d rows, %d bytes' % (len(data['c']) + len(data['asm']), total))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--list', action='store_true')
    parser.add_argument('--only', nargs='*', default=None)
    args = parser.parse_args(argv)
    if args.write:
        write({int(value, 0) for value in args.only} if args.only else None)
    if args.list or not args.write:
        listing()
    return 0


if __name__ == '__main__':
    sys.exit(main())
